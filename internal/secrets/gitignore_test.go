// The tests of the .gitignore plan (bash: tests/unit/secrets_test.bats).
// The fixtures are literal strings, not the constants of the code: a change
// of the block or of a refusal text must change a test too. Each refusal
// line names the file, the line number and the reason, never the rule.

const (
	testGitignoreRel = ".secrets/.gitignore"

	litBegin = "# BEGIN lok8s secrets. lo rewrites the lines up to the END line: add your own rules below it."
	litEnd   = "# END lok8s secrets"
	litBlock = "# BEGIN lok8s secrets. lo rewrites the lines up to the END line: add your own rules below it.\n" +
		"# Ignore everything except this file and the SOPS-encrypted secret files.\n" +
		"# A plaintext secret file must never be committed.\n" +
		"*\n" +
		"!.gitignore\n" +
		"!Secret.*.enc\n" +
		"*/\n" +
		"# END lok8s secrets\n"
	litLegacy = "# Auto-generated by lok8s — ignore everything except SOPS-encrypted\n" +
		"# secret cache files. Plaintext cache entries must never be committed.\n" +
		"*\n" +
		"!.gitignore\n" +
		"!Secret.*.enc\n"
	litBOM = "\xef\xbb\xbf"

	litNegation = "this negation can re-include a plaintext secret file (the last matching rule wins): remove the line, or keep the file outside the store"
	litInside   = "this rule is in the lok8s block, which lo rewrites: move it below the END line"
	litMarker   = "the BEGIN and END lines of the lok8s block must occur once each, with BEGIN first"
)

// litFinal is the last refusal line of a check that stops before step.
func litFinal(rel, step string) string {
	return rel + " was not changed, and lo stopped before " + step + ": fix each cause above, then run this command again"
}

func lineRefusal(n, text string) string {
	return testGitignoreRel + ":" + n + ": " + text
}

// crlf is s with each newline as CR LF.
func crlf(s string) string { return strings.ReplaceAll(s, "\n", "\r\n") }

func TestPlanGitignore(t *testing.T) {
	for _, tc := range []struct {
		name, raw, want string
		problems        []string
	}{
		{name: "an empty file gets the block", raw: "", want: litBlock},
		{name: "a file with comments only gets the block on top",
			raw:  "# *\n# !Secret.*.enc\n",
			want: litBlock + "# *\n# !Secret.*.enc\n"},
		{name: "a file with no block gets it on top, and its lines follow it",
			raw:  "mine\n/tmp/\n",
			want: litBlock + "mine\n/tmp/\n"},
		{name: "a last line with no newline stays so",
			raw:  "mine",
			want: litBlock + "mine"},
		{name: "the legacy lines get the block in their place",
			raw:  litLegacy + "extra\n",
			want: litBlock + "extra\n"},
		{name: "the legacy lines with CRLF",
			raw:  crlf(litLegacy) + "extra\r\n",
			want: litBlock + "extra\r\n"},
		{name: "a current block keeps the lines above and below it",
			raw:  "above\n" + litBlock + "below\n\\!x\n",
			want: "above\n" + litBlock + "below\n\\!x\n"},
		{name: "a changed block becomes the block, the CRLF lines above stay",
			raw: "above\r\n" + litBegin + "\r\n# an old comment\n*\n!.gitignore\n!Secret.*.enc\n" +
				litEnd + "\n" + "below\n\n# note\nlast",
			want: "above\r\n" + litBlock + "below\n\n# note\nlast"},
		{name: "a rule above the block has no effect and stays",
			raw:  "!*\n!plain\n" + litBlock,
			want: "!*\n!plain\n" + litBlock},
		{name: "a rule and a negation inside the block are refused",
			raw: litBegin + "\n# mine\n*\n*.log\n!x\n!.gitignore\n!Secret.*.enc\n*/\n" + litEnd + "\n",
			problems: []string{
				lineRefusal("4", litInside),
				lineRefusal("5", litNegation)}},
		{name: "each negation below the block is refused",
			raw: litBlock + "![x/Secret.].enc\n!Secret.*.ENC\n!?\n!README.md\n!Secret.x.enc\n!.gitignore\n!\n",
			problems: []string{
				lineRefusal("9", litNegation),
				lineRefusal("10", litNegation),
				lineRefusal("11", litNegation),
				lineRefusal("12", litNegation),
				lineRefusal("13", litNegation),
				lineRefusal("14", litNegation),
				lineRefusal("15", litNegation)}},
		{name: "an escaped !, a leading space and positive rules below the block pass",
			raw:  litBlock + "\\!x\n !x\n*.log\nSecret.*.enc\n",
			want: litBlock + "\\!x\n !x\n*.log\nSecret.*.enc\n"},
		{name: "a comment and an empty line before a negation: the line number counts them",
			raw:      litBlock + "# note\n\n!plain\n",
			problems: []string{lineRefusal("11", litNegation)}},
		{name: "a negation in a file with no block",
			raw:      "x\n!plain\n",
			problems: []string{lineRefusal("2", litNegation)}},
		{name: "a negation below the legacy lines",
			raw:      litLegacy + "!*\n",
			problems: []string{lineRefusal("6", litNegation)}},
		{name: "a control byte and a CR in a refused line",
			raw: litBlock + "!\x1b[2Jx\n!plain\r\n",
			problems: []string{
				lineRefusal("9", litNegation),
				lineRefusal("10", litNegation)}},
		{name: "two BEGIN lines are refused",
			raw: litBegin + "\n" + litBegin + "\n" + litEnd + "\n",
			problems: []string{
				lineRefusal("1", litMarker),
				lineRefusal("2", litMarker),
				lineRefusal("3", litMarker)}},
		{name: "END before BEGIN is refused",
			raw: litEnd + "\n" + litBegin + "\n",
			problems: []string{
				lineRefusal("1", litMarker),
				lineRefusal("2", litMarker)}},
		{name: "a NUL byte is refused",
			raw:      "a\x00b\n",
			problems: []string{testGitignoreRel + ": the file has a NUL byte, and git ends a rule at that byte: remove it"}},
		{name: "a plan at the size limit passes",
			raw:  strings.Repeat("#", 1048576-len(litBlock)),
			want: litBlock + strings.Repeat("#", 1048576-len(litBlock))},
		{name: "a plan one byte over the size limit is refused",
			raw:      strings.Repeat("#", 1048576-len(litBlock)+1),
			problems: []string{testGitignoreRel + ": with the lok8s block the file would have more than 1048576 bytes, and lo does not read a larger .gitignore: make it smaller"}},
		{name: "a file at the size limit is read, and its plan with the block is refused",
			raw:      strings.Repeat("#", 1048576),
			problems: []string{testGitignoreRel + ": with the lok8s block the file would have more than 1048576 bytes, and lo does not read a larger .gitignore: make it smaller"}},
		{name: "a short block that grows past the size limit is refused",
			raw:      litBegin + "\n" + litEnd + "\n" + strings.Repeat("#", 1048576-len(litBlock)+1),
			problems: []string{testGitignoreRel + ": with the lok8s block the file would have more than 1048576 bytes, and lo does not read a larger .gitignore: make it smaller"}},
		{name: "a file larger than the size limit is refused",
			raw:      strings.Repeat("#", 1048577),
			problems: []string{testGitignoreRel + ": the file has more than 1048576 bytes, and lo does not read a larger .gitignore: make it smaller"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			planCase(t, tc.raw, tc.want, tc.problems)
		})
	}
}

// planCase checks the plan of raw: the refusal lines, or the bytes of the
// plan.
func planCase(t *testing.T, raw, want string, problems []string) {
	t.Helper()
	got, gotProblems := storeguard.PlanGitignore([]byte(raw), testGitignoreRel)
	if !slices.Equal(gotProblems, problems) {
		t.Errorf("problems:\n%q\nwant:\n%q", gotProblems, problems)
	}
	if problems != nil {
		if got != nil {
			t.Errorf("a refused file has a plan: %q", got)
		}
		return
	}
	if string(got) != want {
		t.Errorf("plan:\n%q\nwant:\n%q", got, want)
	}
}

// Git skips a UTF-8 BOM only at the start of a .gitignore. The plan reads
// the first line without it and keeps it at the start: a BOM before BEGIN
// still finds the block, and a file with no block gets the block after the
// BOM.
func TestPlanGitignoreKeepsTheBOMAtTheStart(t *testing.T) {
	for _, tc := range []struct {
		name, raw, want string
		problems        []string
	}{
		{name: "a BOM before BEGIN: the block is current",
			raw:  litBOM + litBlock + "below\n",
			want: litBOM + litBlock + "below\n"},
		{name: "a BOM before a changed block",
			raw:  litBOM + litBegin + "\n*\n" + litEnd + "\n",
			want: litBOM + litBlock},
		{name: "a BOM in a file with no block: the block goes after it",
			raw:  litBOM + "mine\n",
			want: litBOM + litBlock + "mine\n"},
		{name: "a BOM before the legacy lines",
			raw:  litBOM + litLegacy + "x\n",
			want: litBOM + litBlock + "x\n"},
		{name: "a BOM and nothing else",
			raw:  litBOM,
			want: litBOM + litBlock},
		{name: "a BOM before a negation on the first line",
			raw:      litBOM + "!plain\n",
			problems: []string{lineRefusal("1", litNegation)}},
		{name: "a BOM on line 3 is bytes of that line, not a second start",
			raw:  "a\nb\n" + litBOM + "!plain\n",
			want: litBlock + "a\nb\n" + litBOM + "!plain\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			planCase(t, tc.raw, tc.want, tc.problems)
		})
	}
}

// A refusal prints the file, the line number and the reason. It never
// prints the rule, which can hold a pasted secret, and a byte of the path
// outside the printable ASCII range shows as ?.
func TestGitignoreRefusalNeverPrintsTheRule(t *testing.T) {
	raw := "above\n" + litBegin + "\nPASSWORD=hunter2\n*\n!.gitignore\n!Secret.*.enc\n*/\n" + litEnd + "\n!API_TOKEN=s3cr3t-value\n"
	for _, tc := range []struct{ name, store, rel string }{
		{"the flat store", ".secrets", ".secrets/.gitignore"},
		{"a store name with a control byte", "st\x1b[2Jore", "st?[2Jore/.gitignore"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c, out, errOut := testEnv(t)
			dir := c.Paths.Base + "/" + tc.store
			write(t, dir+"/.gitignore", raw)
			before := fileStates(t, c.Paths.Base)
			if err := c.ensureGitignore(dir, stepPlaintext); !errors.Is(err, ErrHandled) {
				t.Fatalf("want ErrHandled, got %v\n%s", err, errOut.String())
			}
			want := "[error] " + tc.rel + ":3: " + litInside + "\n" +
				"[error] " + tc.rel + ":9: " + litNegation + "\n" +
				"[error] " + litFinal(tc.rel, "the plaintext write") + "\n"
			if errOut.String() != want || out.String() != "" {
				t.Errorf("stdout %q\nstderr:\n%q\nwant:\n%q", out.String(), errOut.String(), want)
			}
			for _, secret := range []string{"hunter2", "s3cr3t", "PASSWORD", "API_TOKEN", "\x1b"} {
				if strings.Contains(errOut.String(), secret) {
					t.Errorf("the refusal prints %q", secret)
				}
			}
			sameStates(t, before, fileStates(t, c.Paths.Base))
		})
	}
}

// gitWouldAdd makes a git repository in a new temp dir with the store
// .secrets/ in it: the .gitignore with the bytes gitignore, and the files
// of storeFiles. It returns what `git add --dry-run -A` would add, sorted.
// The git config of the host is not read (GIT_CONFIG_NOSYSTEM, an empty
// global config, HOME in a temp dir). A missing git fails the test.
func gitWouldAdd(t *testing.T, gitignore string, ignorecase bool) []string {
	t.Helper()
	gitBin, err := exec.LookPath("git")
	if err != nil {
		t.Fatalf("this test needs git: %v", err)
	}
	repo, home := t.TempDir(), t.TempDir()
	env := []string{
		"PATH=" + os.Getenv("PATH"), "HOME=" + home, "LC_ALL=C",
		"GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null",
	}
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.Command(gitBin, args...)
		cmd.Dir, cmd.Env = repo, env
		var stdout, stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		if err := cmd.Run(); err != nil {
			t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, stderr.String())
		}
		return stdout.String()
	}
	git("init", "-q")
	for rel, content := range storeFiles {
		write(t, repo+"/.secrets/"+rel, content)
	}
	write(t, repo+"/.secrets/.gitignore", gitignore)
	var added []string
	ic := "core.ignorecase=false"
	if ignorecase {
		ic = "core.ignorecase=true"
	}
	for l := range strings.SplitSeq(strings.TrimSpace(git("-c", ic, "-c", "core.quotepath=off", "add", "--dry-run", "-A")), "\n") {
		if l != "" {
			added = append(added, strings.TrimSuffix(strings.TrimPrefix(l, "add '"), "'"))
		}
	}
	sort.Strings(added)
	return added
}

// storeFiles is the store of the git tests: a plaintext and its ciphertext,
// a directory Secret.x.enc/ whose .gitignore re-includes its plaintext
// child, the restore.d/ and tls/ directories, and a file of the user.
var storeFiles = map[string]string{
	"Secret.app.default.K":              "plain",
	"Secret.app.default.K.enc":          "cipher",
	"Secret.x.enc/.gitignore":           "!*\n",
	"Secret.x.enc/Secret.app.default.P": "plain",
	"Secret.y.enc/Secret.a.b.c.enc":     "cipher",
	"restore.d/.gitignore":              "!*\n",
	"restore.d/app.yaml":                "plain",
	"tls/tls.key":                       "plain",
	"README.md":                         "notes",
}

// Git is the oracle: with each .gitignore that the plan writes, git would
// commit only the .gitignore and the ciphertext of the top of the store,
// with core.ignorecase off and on. The rules above the block (also the
// negations there) and the accepted rules below it change nothing.
func TestGitignoreKeepsPlaintextOutOfGit(t *testing.T) {
	want := []string{".secrets/.gitignore", ".secrets/Secret.app.default.K.enc"}
	for _, tc := range []struct{ name, raw string }{
		{"no file", ""},
		{"rules above and below the block",
			"!*\n!Secret.app.default.K\n!restore.d/\n!Secret.x.enc/\n" + litBlock + "\\!x\n*.log\n# note\n\n"},
		{"a BOM and a file with no block", litBOM + "mine\n"},
		{"the legacy lines", litLegacy + "extra\n"},
		{"a BOM on line 3 below the block", litBlock + "a\nb\n" + litBOM + "!Secret.app.default.K\n"},
	} {
		plan, problems := storeguard.PlanGitignore([]byte(tc.raw), testGitignoreRel)
		if problems != nil {
			t.Fatalf("%s: refused: %q", tc.name, problems)
		}
		for _, ignorecase := range []bool{false, true} {
			if got := gitWouldAdd(t, string(plan), ignorecase); !slices.Equal(got, want) {
				t.Errorf("%s, core.ignorecase=%v: git would add\n%q\nwant:\n%q", tc.name, ignorecase, got, want)
			}
		}
	}
}

// ensureGitignore writes the plan, keeps each line of the user, and writes
// nothing when the file has the bytes of the plan. A file with comments only
// is not current: the old check read the allow line in a comment.
func TestEnsureGitignoreKeepsTheLinesOfTheUser(t *testing.T) {
	for _, tc := range []struct{ name, raw, want string }{
		{"comments only", "# *\n# !Secret.*.enc\n", litBlock + "# *\n# !Secret.*.enc\n"},
		{"above and below",
			"above\n" + litBegin + "\n# old\n*\n!.gitignore\n!Secret.*.enc\n" + litEnd + "\nbelow\nlast",
			"above\n" + litBlock + "below\nlast"},
		{"legacy", litLegacy + "mine\n", litBlock + "mine\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c, _, errOut := testEnv(t)
			dir := c.Paths.Base + "/.secrets"
			write(t, dir+"/.gitignore", tc.raw)
			if err := c.ensureGitignore(dir, stepPlaintext); err != nil {
				t.Fatalf("%v\n%s", err, errOut.String())
			}
			if got := readFile(t, dir+"/.gitignore"); got != tc.want {
				t.Errorf(".gitignore:\n%q\nwant:\n%q", got, tc.want)
			}
			before := fileStates(t, dir)
			if err := c.ensureGitignore(dir, stepPlaintext); err != nil {
				t.Fatalf("the second run: %v\n%s", err, errOut.String())
			}
			sameStates(t, before, fileStates(t, dir))
		})
	}
}

// A refused .gitignore: the refusal lines with the step of the command,
// ErrHandled, and nothing written.
func refusedGitignore(t *testing.T, c *Context, errOut *bytes.Buffer, err error, before map[string]string, step string) {
	t.Helper()
	want := "[error] " + lineRefusal("9", litNegation) + "\n" +
		"[error] " + litFinal(testGitignoreRel, step) + "\n"
	if !errors.Is(err, ErrHandled) {
		t.Fatalf("want ErrHandled, got %v\n%s", err, errOut.String())
	}
	if errOut.String() != want {
		t.Errorf("stderr:\n%q\nwant:\n%q", errOut.String(), want)
	}
	sameStates(t, before, fileStates(t, c.Paths.Base))
}

const reIncluding = "!Secret.app.default.K\n"

// A rerun of init with a config writes no config, but it checks the
// .gitignore of the store and writes it when it needs a change, in both
// branches: the key in the config, and another key (bash:
// tests/unit/secrets_test.bats).
func TestInitRerunChecksTheGitignore(t *testing.T) {
	for _, listed := range []bool{true, false} {
		name := "the key in the config"
		if !listed {
			name = "another key in the config"
		}
		t.Run(name, func(t *testing.T) {
			c, out, errOut := testEnv(t)
			_, pubPath := testSSHKeypair(t, c.Paths.Base)
			agePubkey, err := deriveAgePublicKey(pubPath)
			if err != nil {
				t.Fatal(err)
			}
			if !listed {
				agePubkey = keyA
			}
			sopsRules(t, c, agePubkey)
			gitignore := c.Paths.Base + "/.secrets/.gitignore"
			write(t, gitignore, litLegacy+"mine\n")
			if err := c.Init(pubPath); err != nil {
				t.Fatalf("%v\n%s", err, errOut.String())
			}
			if got := readFile(t, gitignore); got != litBlock+"mine\n" {
				t.Errorf(".gitignore: %q", got)
			}
			if listed && out.String() != "age key already configured in .sops.yaml\n" {
				t.Errorf("stdout %q", out.String())
			}

			write(t, gitignore, litBlock+reIncluding)
			out.Reset()
			errOut.Reset()
			before := fileStates(t, c.Paths.Base)
			refusedGitignore(t, c, errOut, c.Init(pubPath), before, "its first write")
			if out.String() != "" {
				t.Errorf("stdout %q", out.String())
			}
		})
	}
}

// set checks the .gitignore before it writes the plaintext: a store with no
// .gitignore gets it, and a refused one stops the run with no plaintext
// (bash: tests/unit/secrets_test.bats).
func TestSetChecksTheGitignoreBeforeThePlaintext(t *testing.T) {
	c, _, errOut := testEnv(t)
	if err := c.Set(context.Background(), "app", "default", "K", "v", false); err != nil {
		t.Fatalf("%v\n%s", err, errOut.String())
	}
	dir := c.Paths.Base + "/.secrets"
	if got := readFile(t, dir+"/.gitignore"); got != litBlock {
		t.Errorf(".gitignore: %q", got)
	}
	if err := os.Remove(dir + "/Secret.app.default.K"); err != nil {
		t.Fatal(err)
	}

	write(t, dir+"/.gitignore", litBlock+reIncluding)
	errOut.Reset()
	before := fileStates(t, c.Paths.Base)
	refusedGitignore(t, c, errOut, c.Set(context.Background(), "app", "default", "K", "v", false), before, "the plaintext write")
}

// set refuses a key that makes the plaintext name end in .enc, in any
// letter case, before any write and before it reads the value: the rule
// !Secret.*.enc of the .gitignore re-includes that name (bash:
// tests/unit/secrets_test.bats). The refusal names the key and the file,
// never the value. A key that ends in ENC without the dot is written.
func TestSetRefusesAKeyThatEndsInEnc(t *testing.T) {
	for _, key := range []string{"enc", "ENC", "password.enc", "Password.Enc"} {
		t.Run(key, func(t *testing.T) {
			c, out, errOut := testEnv(t)
			before := fileStates(t, c.Paths.Base)
			err := c.Set(context.Background(), "app", "default", key, "the-value", false)
			if !errors.Is(err, ErrHandled) {
				t.Fatalf("want ErrHandled, got %v\n%s", err, errOut.String())
			}
			want := "[error] the key '" + key + "' is refused: the plaintext file Secret.app.default." + key +
				" would end in .enc (in any letter case), and the .gitignore rule !Secret.*.enc lets git commit it." +
				" Nothing was written: use a key name that does not end in .enc\n"
			if errOut.String() != want || out.String() != "" {
				t.Errorf("stdout %q\nstderr:\n%q\nwant:\n%q", out.String(), errOut.String(), want)
			}
			if strings.Contains(errOut.String(), "the-value") {
				t.Error("the refusal prints the value")
			}
			sameStates(t, before, fileStates(t, c.Paths.Base))
		})
	}
	c, _, errOut := testEnv(t)
	if err := c.Set(context.Background(), "app", "default", "NOT_ENC", "v", false); err != nil {
		t.Fatalf("the control: %v\n%s", err, errOut.String())
	}
	if got := readFile(t, c.Paths.Base+"/.secrets/Secret.app.default.NOT_ENC"); got != "v" {
		t.Errorf("the control: %q", got)
	}
}

