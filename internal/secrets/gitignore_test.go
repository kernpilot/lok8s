// decrypt refuses, before any write and before it looks for the age key, a
// ciphertext whose plaintext name ends in .enc in any letter case: the rule
// !Secret.*.enc of the .gitignore re-includes that name (bash:
// tests/unit/secrets_test.bats). Each such file has a line, in the order of
// the store.
func TestDecryptRefusesAPlaintextNameThatEndsInEnc(t *testing.T) {
	c, out, errOut := testEnv(t)
	dir := c.Paths.Base + "/.secrets"
	for _, base := range []string{"Secret.app.default.K.enc", "Secret.app.default.enc.enc", "Secret.app.default.PW.ENC.enc"} {
		write(t, dir+"/"+base, encEnvelope(keyA))
	}
	before := fileStates(t, c.Paths.Base)
	if err := c.Decrypt(c.Paths.Base + "/no-key"); !errors.Is(err, ErrHandled) {
		t.Fatalf("want ErrHandled, got %v\n%s", err, errOut.String())
	}
	rule := ", which ends in .enc (in any letter case), and the .gitignore rule !Secret.*.enc lets git commit it\n"
	want := "[error] .secrets/Secret.app.default.PW.ENC.enc: decrypt would write the plaintext file Secret.app.default.PW.ENC" + rule +
		"[error] .secrets/Secret.app.default.enc.enc: decrypt would write the plaintext file Secret.app.default.enc" + rule +
		"[error] decrypt wrote no plaintext file: move these .enc files out of the store, then run this command again\n"
	if errOut.String() != want || out.String() != "" {
		t.Errorf("stdout %q\nstderr:\n%q\nwant:\n%q", out.String(), errOut.String(), want)
	}
	sameStates(t, before, fileStates(t, c.Paths.Base))
}

